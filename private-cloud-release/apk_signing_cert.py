"""Parse APK signer certificate output without weakening APK verification.

This module only parses output generated by an independently successful
`apksigner verify --verbose --print-certs <apk>` command. It does not validate
APK signatures itself, and must not replace that verification step.
"""
from __future__ import annotations

import re

_ANSI = re.compile(r"\x1b\[[0-9;]*m")
_CERT = re.compile(
    r"^\s*(?:Signer\s*#\s*1\s+certificate|V[23]\s+Signer\s*:\s*certificate)"
    r"\s+SHA[-\s]?256\s+(?:digest|fingerprint)\s*:\s*(.*?)\s*$",
    re.IGNORECASE,
)
_OTHER_SIGNER = re.compile(r"^\s*Signer\s*#\s*([2-9]\d*)\s+certificate\s+SHA", re.IGNORECASE)


def signing_certificate_sha256(apksigner_output: str) -> str:
    """Return the single APK signing certificate's SHA-256 digest in hex.

    Accept compact, colon-delimited or space-delimited hexadecimal output.
    Never substitute the APK file hash or the keystore hash: certificate pinning
    requires the identity actually reported for the APK being published.
    """
    lines = [_ANSI.sub("", s).strip() for s in apksigner_output.splitlines()]
    if any(_OTHER_SIGNER.match(line) for line in lines):
        raise ValueError("Multiple APK signers detected; this publisher expects a single signing identity")
    for i, line in enumerate(lines):
        match = _CERT.match(line)
        if not match:
            continue
        value = match.group(1).strip()
        if not value and i + 1 < len(lines):
            value = lines[i + 1]
        if value.lower().startswith("0x"):
            value = value[2:]
        normalized = re.sub(r"[\s:]", "", value)
        if re.fullmatch(r"[0-9a-fA-F]{64}", normalized):
            return normalized.lower()
        raise ValueError(
            "APK signing certificate SHA-256 field is not 32 bytes of hex: "
            f"{value[:100]!r}. Run `apksigner verify --verbose --print-certs <apk>` to inspect it."
        )
    samples = [s[:130] for s in lines if "signer" in s.lower() or "certificate" in s.lower()]
    raise ValueError(
        "Unable to extract APK signing certificate fingerprint from apksigner output. "
        "Expected 'Signer #1 certificate SHA-256 digest: <64 hex digits>'. "
        f"Relevant output: {samples[:8]!r}. "
        "Run `apksigner verify --verbose --print-certs <apk>` and check which apksigner is on PATH."
    )
